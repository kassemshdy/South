"""The partner API's OpenAPI file matches the code.

``docs/partner-api-v1.openapi.json`` is handed to partners' developers, so a
route or field that changes without it would mislead them. It is generated by
``scripts/partner_openapi.py``; regenerate it rather than editing it.
"""

from __future__ import annotations

from scripts import partner_openapi


def test_the_committed_spec_is_what_the_code_produces() -> None:
    assert partner_openapi.OUTPUT.read_text(encoding="utf-8") == partner_openapi.render(), (
        "docs/partner-api-v1.openapi.json is out of date: run "
        "`python -m scripts.partner_openapi` in backend/ and commit the result"
    )


def test_the_spec_describes_only_the_partner_feed() -> None:
    spec = partner_openapi.build()
    assert set(spec["paths"]) == set(partner_openapi.ROUTES)
    assert all(path.startswith("/api/partner/v1/") for path in spec["paths"])
    assert spec["servers"][0]["url"] == "https://www.janoubona.net"
    for operation in (ops["get"] for ops in spec["paths"].values()):
        assert operation["security"] == [{"PartnerKey": []}]
        assert {"200", "401", "403", "429"} <= set(operation["responses"])


def test_no_private_field_is_in_the_spec() -> None:
    """The feed is public data only; its spec must not even name an identity field."""
    text = partner_openapi.render()
    for private in ("owner_identity", "owner_phone", "password", "national_id", "birth"):
        assert private not in text
